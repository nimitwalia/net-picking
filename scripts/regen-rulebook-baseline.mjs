#!/usr/bin/env node
// Regenerate apps/free/tests/baselines/rulebook-baseline.json from the BUILD (apps/free/dist) and apps/free/public.
// Run:  pnpm --filter @net-picking/free build && pnpm regen:rulebook-baseline
// It never builds (tests and tools do not build dist; see apps/free/tests/e2e/require-dist.ts). It prints which text
// runs were added or removed compared with the committed file, so review that list before committing: every added
// run is prose the app now ships, and the rulebook-link spec exists to stop unreviewed prose.
// The Rules card note ("Opens in your browser and needs internet.") is deliberately NOT stored: the spec allows it
// by name, and storing it would make the "no new prose" check unable to notice it disappearing or being duplicated.
// Text runs use the same rules as rulebook-link.spec.ts (runsOf): <style> removed, split on quotes, backticks,
// angle brackets and newlines, then keep runs of 40+ characters that contain a space.
// Zero dependencies.
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DIST = join(REPO, "apps/free/dist");
const PUB = join(REPO, "apps/free/public");
const OUT = join(REPO, "apps/free/tests/baselines/rulebook-baseline.json");
const NOTE = "Opens in your browser and needs internet.";
const PUBLIC_FILES = ["sw.js", "manifest.webmanifest", "icon-192.png", "icon-512.png", "apple-touch-icon.png"];

export function runsOf(text) {
  return text
    .replace(/<style[\s\S]*?<\/style>/g, "")
    .split(/["'`<>\n]|\\n/)
    .map((s) => s.trim())
    .filter((s) => s.length >= 40 && /\s/.test(s));
}

function main() {
  for (const f of ["index.html", "assets/main.js", "sw.js"]) {
    if (!existsSync(join(DIST, f))) {
      console.error(`apps/free/dist/${f} is missing. Run: pnpm --filter @net-picking/free build`);
      process.exit(1);
    }
  }
  const text = ["index.html", "assets/main.js"].map((f) => readFileSync(join(DIST, f), "utf8")).join("\n");
  const textRuns = [...new Set(runsOf(text))].filter((r) => r !== NOTE).sort();
  const publicSha256 = {};
  for (const f of PUBLIC_FILES) publicSha256[f] = createHash("sha256").update(readFileSync(join(PUB, f))).digest("hex");
  const cacheName = readFileSync(join(DIST, "sw.js"), "utf8").match(/net-picking-v\d+/)?.[0];
  if (!cacheName) { console.error("no net-picking-v<n> cache name in dist/sw.js"); process.exit(1); }
  let head = "unknown";
  try { head = execFileSync("git", ["rev-parse", "--short", "HEAD"], { cwd: REPO, encoding: "utf8" }).trim(); } catch { /* not a git checkout */ }

  let before = { textRuns: [] };
  try { before = JSON.parse(readFileSync(OUT, "utf8")); } catch { /* first run */ }
  const was = new Set(before.textRuns), now = new Set(textRuns);
  const added = textRuns.filter((r) => !was.has(r)), removed = before.textRuns.filter((r) => !now.has(r));

  const json = {
    note: `Generated by scripts/regen-rulebook-baseline.mjs from the build at ${head}: text runs >= 40 chars with a space found in dist/index.html + dist/assets/main.js (Rules card note excluded), and sha256 of the public files that must not change.`,
    cacheName,
    publicSha256,
    textRuns,
  };
  writeFileSync(OUT, JSON.stringify(json, null, 1) + "\n");
  console.log(`wrote ${OUT}: ${textRuns.length} text runs, ${added.length} added, ${removed.length} removed`);
  for (const r of added) console.log(`  + ${r}`);
  for (const r of removed) console.log(`  - ${r}`);
}
main();
